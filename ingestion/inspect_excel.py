"""Document every sheet and column of the Excel files:  python -m ingestion.inspect_excel [--input-dir DIR]

Writes docs/excel_inspection.md in English (column names are shown with their English names).
"""
import argparse
from pathlib import Path

import pandas as pd

from . import config
from .labels import EVENT_HEADERS, TRAFFIC_HEADERS
from .excel_utils import norm_ar, read_sheet

NOTES = """## Notes

- **Traffic grain:** one source row = one industrial city + one month + one direction (entry or exit) + a vehicle count.
  The files are monthly, not daily. The cleaned table has one row per city and month.
- **Traffic Q1 vs Q2 layouts:** `Traffic_4` (Q1) has 6 columns, the 6th holds only a footnote about the cameras;
  `Traffic_3` (Q2) has 5 columns. Both have a title row, so the header is on Excel row 2. The two quarters also
  cover different cities (for example Al-Kharj and Zulfi appear only in Q1; Hafr Al-Batin only in Q2).
- **Events grain:** one source row = one approved government event request (`request_number`).
- **Events Q1 vs Q2 layouts:** Q1 has 10 columns (including attendance) and calls the venue category
  "event type (venue)"; Q2 has 9 columns (no attendance) and calls it "venue type". Q2 also repeats many Q1 events,
  so duplicates are removed by `request_number`.
- **Events source:** public sector event approvals lists provided with the programme. Publisher and licence still
  to be confirmed with the team.
"""


def describe(path: Path, headers: dict) -> list:
    lookup = {alias: english for english, aliases in headers.items() for alias in aliases}
    lines = [f"## {path.name}", ""]
    for number, sheet in enumerate(pd.ExcelFile(path).sheet_names, start=1):
        raw = pd.read_excel(path, sheet_name=sheet, header=None, dtype=object)
        lines.append(f"### Sheet {number} ({len(raw)} rows x {raw.shape[1]} columns)")
        result = read_sheet(path, sheet, headers, min_found=4)
        if result is None:
            lines += ["No header row recognised (metadata or empty sheet): skipped.", ""]
            continue
        table, layout_version, header_row = result
        lines += [f"Header row: Excel row {header_row}. Layout version: `{layout_version}`. Data rows: {len(table)}.", "",
                  "| column | non-empty | distinct values |", "|---|---|---|"]
        for column in table.columns:
            if column != "source_row":
                lines.append(f"| {column} | {int(table[column].notna().sum())} | {table[column].nunique()} |")
        recognised = {norm_ar(v) for v in raw.iloc[header_row - 1] if pd.notna(v) and norm_ar(v) in lookup}
        extra = int(raw.iloc[header_row - 1].notna().sum()) - len(recognised)
        lines += ["", f"Columns that are not used: {max(extra, 0)} (plus any notes outside the table).", ""]
    return lines


def main(input_dir: Path):
    out = ["# Excel inspection", "", "Generated by `python -m ingestion.inspect_excel`.", ""]
    for file in sorted(input_dir.glob(config.TRAFFIC_GLOB)):
        out += describe(file, TRAFFIC_HEADERS)
    for file in sorted(input_dir.glob(config.EVENTS_GLOB)):
        out += describe(file, EVENT_HEADERS)
    out.append(NOTES)
    target = config.ROOT / "docs" / "excel_inspection.md"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--input-dir", type=Path, default=config.ROOT)
    main(parser.parse_args().input_dir)
